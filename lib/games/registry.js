export function getGameById(id) {
  return GAMES_REGISTRY.find((g) => g.id === id) || GAMES_REGISTRY[0];
}

export function getGamesByCategory(category) {
  if (!category || category === GAME_CATEGORIES.ALL) return GAMES_REGISTRY;
  return GAMES_REGISTRY.filter((g) => g.category === category);
}

export function getAvailableGames() {
  return GAMES_REGISTRY.filter((g) => g.isLive);
}
